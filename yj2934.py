def es(losses, alpha=None, VaR=None):
    """
    Calculate ES as the mean of losses strictly exceeding VaR.

    losses: positively stated loss values
    alpha: confidence level, such as 0.80
    VaR: an explicitly supplied loss threshold
    """

    losses = np.asarray(losses, dtype=float).reshape(-1)

    if losses.size == 0 or not np.all(np.isfinite(losses)):
        raise ValueError("Losses must be nonempty and finite.")

    if VaR is None:
        if alpha is None or not 0 < alpha < 1:
            raise ValueError(
                "Provide alpha between 0 and 1, or provide VaR."
            )

        # Losses are positively stated:
        # use the alpha percentile for the loss threshold.
        # This corrects the template's (1 - alpha) percentile.
        VaR = np.percentile(losses, 100 * alpha)

    tail_losses = losses[losses > VaR]

    if tail_losses.size == 0:
        raise ValueError("No losses exceed the VaR threshold.")

    return np.mean(tail_losses)



def get_stock_data(symbol):
    """Download daily closing prices for one stock."""

    data = yf.download(
        symbol,
        period="max",
        interval="1d",
        auto_adjust=False,
        multi_level_index=False,
        progress=False
    )

    if data is None or data.empty:
        raise ValueError(
            "No stock data downloaded. Check the connection and rerun."
        )

    prices = data["Close"].dropna().sort_index()

    if len(prices) < 2:
        raise ValueError("At least two prices are needed.")

    return prices


def get_returns(pricevec):
    """Calculate simple returns: P_t / P_(t-1) - 1."""

    pricevec = np.asarray(pricevec, dtype=float).reshape(-1)

    if len(pricevec) < 2:
        raise ValueError("At least two prices are needed.")

    n = len(pricevec)
    ratiovec = pricevec[1:n] / pricevec[:n-1]
    returns = ratiovec - 1

    return returns



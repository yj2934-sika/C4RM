def percent_var(r, alpha):
    """
    Return the positive magnitude of the
    (1 - alpha) return percentile, as required.
    Also display a histogram.
    """

    r = np.asarray(r, dtype=float).reshape(-1)

    if r.size == 0 or not np.all(np.isfinite(r)):
        raise ValueError("Returns must be nonempty and finite.")

    if not 0 < alpha < 1:
        raise ValueError("alpha must be between 0 and 1.")

    out = np.percentile(r, (1 - alpha) * 100)

    plt.figure(figsize=(8, 5))
    plt.hist(r, bins=50, alpha=0.75, edgecolor="white")
    plt.axvline(
        out,
        color="red",
        linestyle="--",
        label=f"Left-tail percentile = {out:.4f}"
    )
    plt.title("Distribution of Simulated Returns")
    plt.xlabel("Return")
    plt.ylabel("Frequency")
    plt.legend()
    plt.tight_layout()
    plt.show()

    return abs(out)



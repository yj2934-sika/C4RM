# Question 1: Bond class
# Assumption: annual coupon payments.
# Duration is Macaulay duration, measured in years.

class Bond:
    def __init__(self, coupon_rate, maturity,
                 face_value, yield_to_maturity):
        self.coupon_rate = coupon_rate
        self.maturity = maturity
        self.face_value = face_value
        self.yield_to_maturity = yield_to_maturity

    def __repr__(self):
        return (
            f"Bond(coupon_rate={self.coupon_rate}, "
            f"maturity={self.maturity}, "
            f"face_value={self.face_value}, "
            f"yield_to_maturity={self.yield_to_maturity})"
        )

    def __str__(self):
        return (
            f"Bond: face value = {self.face_value:,.2f}, "
            f"coupon rate = {self.coupon_rate:.2%}, "
            f"maturity = {self.maturity} years, "
            f"yield to maturity = {self.yield_to_maturity:.2%}"
        )

    def getPrice(self):
        """Calculate the present value of coupons and principal."""
        coupon = self.face_value * self.coupon_rate
        price = 0.0

        for t in range(1, self.maturity + 1):
            cash_flow = coupon

            if t == self.maturity:
                cash_flow += self.face_value

            price += cash_flow / (1 + self.yield_to_maturity) ** t

        return price

    def getDuration(self):
        """Calculate Macaulay duration in years."""
        coupon = self.face_value * self.coupon_rate
        total_pv = 0.0
        weighted_pv = 0.0

        for t in range(1, self.maturity + 1):
            cash_flow = coupon

            if t == self.maturity:
                cash_flow += self.face_value

            present_value = (
                cash_flow / (1 + self.yield_to_maturity) ** t
            )

            total_pv += present_value
            weighted_pv += t * present_value

        return weighted_pv / total_pv


# Question 2: Convertible bond class
# Assumptions: annual coupon payments.
# Price follows the assignment: max(bond value, conversion value).
# Duration is the Macaulay duration of the debt component.

class ConvertibleBond(Bond):
    def __init__(self, face, coupon, yield_rate, maturity,
                 conversion_ratio, stock_price):
        # coupon is the annual cash payment, not the coupon rate.
        super().__init__(
            coupon_rate=coupon / face,
            maturity=maturity,
            face_value=face,
            yield_to_maturity=yield_rate
        )

        self.face = face
        self.coupon = coupon
        self.yield_rate = yield_rate
        self.conversion_ratio = conversion_ratio
        self.stock_price = stock_price

    def __repr__(self):
        return (
            f"ConvertibleBond(face={self.face}, "
            f"coupon={self.coupon}, "
            f"yield_rate={self.yield_rate}, "
            f"maturity={self.maturity}, "
            f"conversion_ratio={self.conversion_ratio}, "
            f"stock_price={self.stock_price})"
        )

    def __str__(self):
        return (
            f"Convertible bond: face value = {self.face:,.2f}, "
            f"annual coupon = {self.coupon:,.2f}, "
            f"yield = {self.yield_rate:.2%}, "
            f"maturity = {self.maturity} years, "
            f"conversion ratio = {self.conversion_ratio}, "
            f"stock price = {self.stock_price:,.2f}"
        )

    def getPrice(self):
        """Return the higher of bond value and conversion value."""
        bond_price = super().getPrice()
        conversion_value = self.conversion_ratio * self.stock_price

        return max(bond_price, conversion_value)

    def getDuration(self):
        """Return the debt component's Macaulay duration in years."""
        return super().getDuration()

